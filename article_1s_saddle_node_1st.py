learning_rate = 1e-2
layers = np.array([1, 10, 10, 10, 10, 1])  # 4 hidden layers

# System's parameter values
alpha = 0.1
beta = 2
h = 0.5
p = 2

# System
def G(p, h, u):
    return u**p / (u**p + h**p)

def F(alpha, beta, r, p, h, u):
    return alpha - beta * u + r * G(p, h, u)

# Finding local minima and maxima
def Local_Max_Min(y,x):
    # Find local minima
    local_indices = (y[1:-1] - y[:-2]) * (y[1:-1] - y[2:]) > 0
    local_values = y[1:-1][local_indices]
    local_x_values = x[1:-1][local_indices]

    return local_x_values, local_values

# Finding Jacobian and eigenvalues of an equilibrium point of a system
def Jacobian_and_eigenvalues(equations, variables, equilibrium_points):
    results = {}
    jacobian_matrix = sp.Matrix([[sp.diff(eq, var) for var in variables] for eq in equations])

    for eq_point in equilibrium_points:
        point_results = {}

        # Ensure eq_point is iterable by making it a list if it's not already
        if not isinstance(eq_point, (list, tuple)):
            eq_point = [eq_point]

        # Substitute the equilibrium point values into the Jacobian matrix.
        substituted_Jacobian = jacobian_matrix.subs(dict(zip(variables, eq_point)))
        point_results['Jacobian'] = substituted_Jacobian

        # Calculate eigenvalues of the substituted Jacobian.
        eigenvalues = substituted_Jacobian.eigenvals()
        point_results['eigenvalues'] = eigenvalues
        results[tuple(eq_point)] = point_results # using tuple as key to avoid unhashable type error
    return results

# Deep neural network

class DNN(nn.Module):
    def __init__(self, layers):
        super().__init__()  # call __init__ from parent class
        'activation function'
        self.activation = nn.Tanh()
        'Initialize neural network as a list using nn.Modulelist'
        self.linears = nn.ModuleList([nn.Linear(layers[i], layers[i + 1]) for i in range(len(layers) - 1)])
        'Xavier Normal Initialization'
        for i in range(len(layers) - 1):
            nn.init.xavier_normal_(self.linears[i].weight.data, gain=1.0)
            # set biases to zero
            nn.init.zeros_(self.linears[i].bias.data)

    'foward pass'

    def forward(self, t):
        # convert to float
        a = t.float()
        for i in range(len(layers) - 2):
            z = self.linears[i](a)
            a = self.activation(z)

        a = self.linears[-1](a)
        return a

# DNN(layers)

class FCN():
    def __init__(self, layers):
        self.loss_function = nn.MSELoss()

        'Call our DNN'
        self.dnn = DNN(layers)

    'loss function'

    def loss_data(self, u):
        uc = u.clone()
        uc.requires_grad = False
        r_hat = torch.zeros(uc.shape[0]).reshape(-1,1)
        r = self.dnn(uc)[:,0].reshape(-1,1)
        # print(t_u)

        loss_r = self.loss_function(F(alpha, beta, r, p, h, uc), r_hat)
        return loss_r

    def loss(self, u):
        loss_r = self.loss_data(u)
        loss_val = loss_r

        return loss_val

PINN = FCN(layers)
